"""Build the Arabic page (ar/index.html) from the English page (index.html).

Why: search engines index the HTML a URL serves. If Arabic only appears after
JavaScript swaps the text, Google sees one English page and Arabic searches
("كرتون استثماري") never find the site. This script writes a real Arabic page at
/ar/ with Arabic text, title, description and dir="rtl" already in the HTML.

Run after every change to index.html:
    python3 tools/build_ar.py

Edit English in index.html and Arabic in the "ar" block of the T dictionary
inside index.html; this script copies the Arabic strings into the page.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = "https://pioneerpaper.org"  # change here (and in index.html) if the domain differs

src = (ROOT / "index.html").read_text(encoding="utf-8")

# 1. Pull the translation dictionary out of the page script.
m = re.search(r"var T = (\{.*?\n\});", src, re.S)
if not m:
    raise SystemExit("Could not find the translation dictionary (var T = {...}) in index.html")
ar = json.loads(m.group(1))["ar"]

out = src

# 2. Put the Arabic text into every element marked data-i18n="key".
out = re.sub(r'(<(\w+)\b[^>]*\bdata-i18n="([^"]+)"[^>]*>)(.*?)(</\2>)',
             lambda m2: m2.group(1) + (ar[m2.group(3)].replace("&", "&amp;").replace("<", "&lt;") if m2.group(3) in ar else m2.group(4)) + m2.group(5),
             out, flags=re.S)

# Image descriptions: <img alt="English" data-alt-ar="Arabic"> gets the Arabic alt text.
out = re.sub(r'alt="[^"]*" data-alt-ar="([^"]*)"', r'alt="\1" data-alt-ar="\1"', out)

# 3. Language and direction on the root elements.
out = out.replace('<html lang="en" dir="ltr">', '<html lang="ar" dir="rtl">', 1)
out = out.replace('<div class="pp" id="pp" dir="ltr" lang="en" data-theme="dark">',
                  '<div class="pp" id="pp" dir="rtl" lang="ar" data-theme="dark">', 1)

# 4. Arabic SEO head.
title = "مصنع كرتون استثماري في مصر والخليج | بايونير للصناعات الورقية"
desc = ("بايونير للصناعات الورقية تصنع الكرتون الاستثماري لأغلفة الكتب والعلب الصلبة والتغليف الفاخر. "
        "سماكات متعددة ومقاسات خاصة، ونورّد إلى مصر والخليج.")
og_desc = "كرتون استثماري لأغلفة الكتب والعلب الصلبة والتغليف الفاخر. سماكات متعددة ومقاسات خاصة، ونورّد إلى مصر والخليج."
head = f'''<!-- seo:start (Arabic; generated by tools/build_ar.py, do not edit by hand) -->
<title>{title}</title>
<meta name="description" content="{desc}">
<link rel="canonical" href="{SITE}/ar/">
<link rel="alternate" hreflang="en" href="{SITE}/">
<link rel="alternate" hreflang="ar" href="{SITE}/ar/">
<link rel="alternate" hreflang="x-default" href="{SITE}/">
<meta name="robots" content="index, follow, max-image-preview:large">
<meta name="theme-color" content="#0A1326">
<meta property="og:type" content="website">
<meta property="og:url" content="{SITE}/ar/">
<meta property="og:title" content="{title}">
<meta property="og:description" content="{og_desc}">
<meta property="og:site_name" content="بايونير للصناعات الورقية">
<meta property="og:locale" content="ar_EG">
<meta property="og:locale:alternate" content="en_US">
<meta property="og:image" content="{SITE}/media/og-image.png">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta property="og:image:alt" content="شعار بايونير للصناعات الورقية">
<meta name="twitter:card" content="summary_large_image">
<script type="application/ld+json">
{{"@context":"https://schema.org","@graph":[
{{"@type":"WebPage","@id":"{SITE}/ar/#page","url":"{SITE}/ar/","name":"{title}","inLanguage":"ar","isPartOf":{{"@id":"{SITE}/#site"}},"about":{{"@id":"{SITE}/#org"}}}}
]}}
</script>
<!-- seo:end -->'''
out = re.sub(r"<!-- seo:start.*?<!-- seo:end -->", lambda _: head, out, count=1, flags=re.S)

# 5. The page lives one folder down, so local files need ../ in front.
out = re.sub(r'(\b(?:src|href)=")(media/|fx/)', r"\1../\2", out)

# 6. The language switch points back to English.
out = out.replace('<a class="tgl" id="langBtn" href="ar/" hreflang="ar" lang="ar" aria-label="العربية">',
                  '<a class="tgl" id="langBtn" href="../" hreflang="en" lang="en" aria-label="English">', 1)
out = out.replace("flags/4x3/sa.svg", "flags/4x3/gb.svg", 1)

(ROOT / "ar").mkdir(exist_ok=True)
(ROOT / "ar" / "index.html").write_text(out, encoding="utf-8")
print("wrote ar/index.html")
